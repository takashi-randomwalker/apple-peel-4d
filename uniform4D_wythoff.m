(* ring patterns up to the reversal symmetry of the diagram *)
w4Patterns[marks_] := Module[{all},
  all = Rest@Tuples[{0, 1}, 4];
  If[marks === Reverse /@ Reverse[marks],
   DeleteDuplicatesBy[all, Sort[{#, Reverse[#]}] &],
   all]];

w4Report[marks_, rings_, note_] := Module[
  {t, r, v, e, f, c, euler, ok, flags},
  {t, r} = AbsoluteTiming[w4Build[marks, rings]];
  {v, e, f, c} = r["counts"];
  euler = v - e + f - c;
  flags = {};
  If[v =!= r["predV"], AppendTo[flags, "V!=|W|/|stab|"]];
  If[c =!= r["predC"], AppendTo[flags, "C!=sum|W|/|W_J|"]];
  If[euler =!= 0,      AppendTo[flags, "chi!=0"]];
  If[r["bad"] > 0,     AppendTo[flags, "non-supporting plane"]];
  If[r["badRidges"] > 0,
     AppendTo[flags, "ridge not in exactly 2 cells"]];
  (* vertex-transitivity: every vertex must have the same degree *)
  If[Length[r["degTally"]] =!= 1, AppendTo[flags, "degree not uniform"]];
  ok = flags === {};
  Print[
   StringPadRight[w4Symbol[marks, rings], 10],
   StringPadLeft[ToString[v], 6], StringPadLeft[ToString[e], 7],
   StringPadLeft[ToString[f], 7], StringPadLeft[ToString[c], 6],
   "  ", If[ok, "OK      ", StringPadRight[StringRiffle[flags, ","], 8]],
   StringPadRight[ToString[r["hist"]], 30],
   StringPadLeft[ToString[Round[t, 0.01]], 7], "s  ", note];
  <|"sym" -> w4Symbol[marks, rings], "counts" -> r["counts"],
    "hist" -> r["hist"], "ok" -> ok, "data" -> r["data"]|>];

w4RunFamily[marks_, name_, notes_] := Module[{pats},
  pats = w4Patterns[marks];
  Print["\n=== ", name, " family : ", Length[pats],
        " Wythoffian members,  |W| = ",
        Length@w4Group[w4Refl /@ w4Normals[marks]], " ==="];
  Print[StringPadRight["symbol", 10], StringPadLeft["V", 6],
        StringPadLeft["E", 7], StringPadLeft["F", 7],
        StringPadLeft["C", 6], "  status  ",
        StringPadRight["cells (nverts -> count)", 30],
        StringPadLeft["time", 7]];
  w4Report[marks, #, Lookup[notes, Key[#], ""]] & /@ pats];

(* write data in _4DData/f*.m format *)
w4Export[path_, data_] := (Export[path, data, "Package"]; path);

