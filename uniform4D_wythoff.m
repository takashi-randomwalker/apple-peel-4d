(* --- cross-check the regular members against _4DData/ --- *)
(* w4Patterns keeps one representative per reversal-pair, so a symbol may
   be stored reversed; look up both spellings. *)
w4Find[sym_] := SelectFirst[w4All,
   #["sym"] === sym || #["sym"] === StringReverse[sym] &];

w4Compare4DData[] := Module[{dir, raw, got, want, eFile, eWyt, r},
  dir = DirectoryName[$InputFileName] <> "_4DData/";
  Print["\n=== cross-check against _4DData/ (V, F, C from parts 1, 4, 6) ==="];
  Do[
   raw   = Get[dir <> file];
   want  = Length /@ raw[[{1, 4, 6}]];
   r     = w4Find[sym];
   got   = r["counts"][[{1, 3, 4}]];
   eFile = Length[Union[Sort /@ raw[[2]]]];
   eWyt  = r["counts"][[2]];
   Print["  ", StringPadRight[file, 7], StringPadRight[sym, 9],
         " file=", want, " wythoff=", got,
         If[want === got, "  MATCH", "  DIFFER"],
         "   edges ", eFile, "/", eWyt,
         If[eFile === eWyt, "", "  (raw part2 = " <> ToString[Length[raw[[2]]]] <> ")"]],
   {p, {{"f5.m", "x3o3o3o"}, {"f8.m", "x4o3o3o"},
        {"f16.m", "o4o3o3x"}, {"f24.m", "x3o4o3o"}}},
   {file, {p[[1]]}}, {sym, {p[[2]]}}]];

